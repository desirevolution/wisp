import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
const win=new Window({url:'http://localhost'});
for(const key of ['document','customElements','HTMLElement','Element','Node','EventTarget','Event','CustomEvent','Document','CSSStyleSheet','MutationObserver','ShadowRoot'])globalThis[key]=win[key];
globalThis.window=win;
await import('../frontend/src/components/wisp-settings.js');
const el=document.createElement('wisp-settings');document.body.append(el);await el.updateComplete;
let calls=0,finish;
globalThis.fetch=async(url,options)=>{calls++;assert.equal(url,'/api/push/test');assert.equal(options.method,'POST');return await new Promise(resolve=>{finish=resolve})};
assert.equal(el.querySelector('.push-test-panel'),null);
await el.sendTestPush();assert.equal(calls,0);
el.pushTestEnabled=true;el.pushSubscriptions=2;await el.updateComplete;
const button=el.querySelector('.push-test-panel button');assert.ok(button);
button.click();await el.updateComplete;assert.equal(button.disabled,true);
await el.sendTestPush();assert.equal(calls,1);
finish(new Response(JSON.stringify({test_id:'test-123',total:2,accepted:1,expired:1,failed:0,results:[{device:'safe-device',provider:'push.example',result:'accepted',http_status:201}]}),{status:200}));
while(el.pushTestBusy)await new Promise(resolve=>setTimeout(resolve,0));await el.updateComplete;
assert.ok(el.textContent.includes('1 of 2 accepted by push providers'));
assert.ok(el.textContent.includes('does not confirm a visible notification'));
assert.ok(el.textContent.includes('safe-device'));assert.equal(button.disabled,false);
globalThis.fetch=async()=>new Response(JSON.stringify({error:'Push testing is disabled'}),{status:403});
await el.sendTestPush();await el.updateComplete;
assert.equal(el.querySelector('[role=alert]').textContent,'Push testing is disabled');
assert.equal(el.pushTestResult,null);
el.pushTestEnabled=false;await el.updateComplete;
assert.equal(el.querySelector('.push-test-panel'),null);
el.remove();await win.happyDOM.close();
console.log('Push settings DOM passed: deployment gate, single broadcast, provider results and errors.');
